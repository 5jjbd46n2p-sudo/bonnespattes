// Nombre de jours avant chaque mois d'une année de 365 jours.
const DAYS_BEFORE = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];

// Rang du jour (0 à 364) pour une date "AAAA-MM-JJ". Le 29 février prend le rang du 28.
export function dayIndex(isoDate) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(isoDate || ""));
  if (!m) return 0;
  const month = Math.min(Math.max(Number(m[2]), 1), 12);
  let day = Math.max(Number(m[3]), 1);
  if (month === 2 && day > 28) day = 28;
  return (DAYS_BEFORE[month - 1] + day - 1) % DAILY_PHRASES.length;
}

export function phraseOfDay(isoDate) {
  return DAILY_PHRASES[dayIndex(isoDate)];
}
